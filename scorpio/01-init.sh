#!/usr/bin/env bash

# https://stackoverflow.com/a/70976611
psql --user "${POSTGRES_USER}" <<-END
CREATE ROLE ${SCORPIO_POSTGRES_USERNAME:?} LOGIN PASSWORD '${SCORPIO_POSTGRES_PASSWORD:?}';

CREATE DATABASE ${SCORPIO_POSTGRES_DATABASE:?} OWNER ${SCORPIO_POSTGRES_USERNAME:?} ENCODING 'UTF8';

\connect ${SCORPIO_POSTGRES_DATABASE:?}

CREATE EXTENSION IF NOT EXISTS postgis CASCADE;
END
